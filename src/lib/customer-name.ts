/**
 * ชื่อที่แสดงแทนลูกค้า
 * ===========================================================================
 * 🔴 กฎเดียวที่สำคัญที่สุด : **ถ้ามีชื่อจริง ต้องใช้ชื่อจริงเสมอ**
 *    ชื่อสำรองมีไว้เพื่อไม่ให้จอว่าง ไม่ใช่ของที่ยอมรับได้ในระยะยาว
 *
 * ⚠️ เหตุผลที่ต้องรวมไว้ที่เดียว :
 *    ก่อนหน้านี้ตรรกะ `c.customer_name || 'ลูกค้า xxxxxx'` ถูกเขียนซ้ำหลายที่
 *    เวลาปรับ (เช่นเพิ่มการตัดช่องว่าง) จะลืมแก้บางจุดเสมอ
 *    แล้วลิสต์กับหัวห้องจะแสดงคนละชื่อ ซึ่งทำให้แอดมินสับสนว่าคุยกับใครอยู่
 */

/** ลูกค้าเท่าที่ต้องรู้เพื่อเลือกชื่อแสดง */
export type NameableCustomer = {
  customer_name?: string | null;
  psid: string;
};

/**
 * ชื่อที่เอาไปแสดงได้เลย
 * ⚠️ ตัดช่องว่างก่อนตัดสิน — ชื่อที่เป็นช่องว่างล้วนต้องนับว่า "ไม่มีชื่อ"
 */
export function displayName(c: NameableCustomer): string {
  const real = (c.customer_name ?? '').trim();
  if (real) return real;
  return fallbackName(c.psid);
}

/**
 * ชื่อสำรองเมื่อยังไม่รู้ชื่อจริง
 * ⭐ ใช้ 6 ตัวท้ายของ psid เพราะสั้นพอจะอ่านออก และต่างกันพอจะแยกคนได้
 *    (psid เต็มยาว 16-17 หลัก อ่านแล้วแยกไม่ออกว่าคนละคน)
 */
export function fallbackName(psid: string): string {
  return `ลูกค้า ${psid.slice(-6)}`;
}

/** ยังไม่รู้ชื่อจริงใช่ไหม — ใช้ตัดสินว่าจะขึ้นปุ่ม "ลองดึงชื่ออีกครั้ง" ไหม */
export function hasRealName(c: NameableCustomer): boolean {
  return (c.customer_name ?? '').trim().length > 0;
}
