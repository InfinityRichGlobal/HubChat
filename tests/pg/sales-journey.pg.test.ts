import { describe, it, expect, beforeAll, afterAll, vi } from 'vitest';
import { randomUUID } from 'node:crypto';
import type { Pool } from 'pg';
import { postgresAvailable, resetDatabase, startRestServer, testPool, type RestServer } from './harness';
const auth = vi.hoisted(() => ({ requireAdmin: vi.fn() }));
vi.mock('@/lib/auth/current-admin', async importOriginal => ({...await importOriginal<Record<string, unknown>>(), requireAdmin:auth.requireAdmin}));
const available = await postgresAvailable();
process.env.NEXT_PUBLIC_SUPABASE_URL = `http://127.0.0.1:${process.env.HUBCHAT_TEST_REST_PORT ?? 54399}`;
process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY = 'a'.repeat(40);
process.env.SUPABASE_SERVICE_ROLE_KEY = 'b'.repeat(40);
process.env.SESSION_SECRET = 'c'.repeat(40);
process.env.ENCRYPTION_KEY = Buffer.alloc(32,5).toString('base64');
const { enqueueWebhook } = await import('@/server/ingest/queue');
const { processWebhookBatch } = await import('@/server/ingest/processor');
const { encryptSecret } = await import('@/lib/crypto');
const { __setFetcherForTests } = await import('@/server/meta/client');
const { markRead, acquireLock, updateCustomerContact, listMessages, requireConversationAccess } = await import('@/server/inbox/service');
const { humanAdminReply } = await import('@/server/messaging/provenance');
const { sendMessage } = await import('@/server/messaging/send-message');
const { createOrder, updateOrder, getOrder, linkOrderMedia } = await import('@/server/orders/service');
const { createImport, applyImport } = await import('@/server/tracking/service');
const { loadDashboard } = await import('@/server/dashboard/service');
const { loadWorkspace } = await import('@/server/customers/workspace');
const { listSendStatuses } = await import('@/server/messaging/status-service');
let pool: Pool; let rest: RestServer;
const page = randomUUID(), ownerId = randomUUID();
let owner: Parameters<typeof createOrder>[0];
describe.skipIf(!available)('sales journey across real PostgreSQL services', () => {
  beforeAll(async () => {
    await resetDatabase(); pool=testPool(); rest=await startRestServer(pool);
    await pool.query("insert into admins(id,name,email,password_hash,role) values($1,'Owner','owner@test.local','x','owner')",[ownerId]);
    await pool.query("insert into pages(id,platform,page_id,page_name,access_token) values($1,'facebook','journey-page','Test',$2)",[page,encryptSecret('FAKE-TOKEN')]);
    owner=(await pool.query('select * from admins where id=$1',[ownerId])).rows[0];
    auth.requireAdmin.mockResolvedValue(owner);
  },120000);
  afterAll(async () => { __setFetcherForTests(null); await rest?.close(); await pool?.end(); });
  it('receive → lock → reply/image → contact → order/slip → packing → tracking → dashboard; viewer and foreign-page actions denied', async () => {
    let sends=0;
    __setFetcherForTests((async (_url, init) => {
      if(init?.method === 'POST') { sends++; return Response.json({message_id:`sent-${sends}`,recipient_id:'journey-customer'}); }
      return Response.json({id:'journey-customer',name:'Test Customer'});
    }) as typeof fetch);
    const now=Date.now();
    await enqueueWebhook({object:'page',entry:[{id:'journey-page',messaging:[{sender:{id:'journey-customer'},recipient:{id:'journey-page'},timestamp:now,message:{mid:'journey-inbound',text:'สนใจสินค้า ขอ 1 ชิ้น'}}]}]});
    const incoming=await processWebhookBatch(); expect(incoming.inbound_saved).toBe(1);
    const conv=(await pool.query('select id,customer_id from conversations')).rows[0];
    await expect(requireConversationAccess({...owner,role:'admin',allowed_page_ids:[]},conv.id)).rejects.toThrow();
    await markRead(owner,conv.id); expect((await acquireLock(owner,conv.id)).won).toBe(true);
    auth.requireAdmin.mockResolvedValue({...owner,role:'viewer'});
    await expect(humanAdminReply()).rejects.toThrow();
    auth.requireAdmin.mockResolvedValue(owner);
    const provenance=await humanAdminReply();
    expect((await sendMessage({conversation_id:conv.id,message_type:'inquiry_response',provenance,content:{text:'สินค้าพร้อมส่งค่ะ'},idempotency_key:'journey-text'})).sent).toBe(true);
    expect((await sendMessage({conversation_id:conv.id,message_type:'inquiry_response',provenance,content:{images:[{url:'https://example.com/test-product.jpg'}]},idempotency_key:'journey-image'})).sent).toBe(true);
    expect(sends).toBe(2);
    await sendMessage({conversation_id:conv.id,message_type:'inquiry_response',provenance,content:{text:'สินค้าพร้อมส่งค่ะ'},idempotency_key:'journey-text'});
    expect(sends).toBe(2);
    await updateCustomerContact(owner,conv.id,{recipient_name:'ผู้ทดสอบ',phone:'0812345678',address:'ที่อยู่ทดสอบ',postcode:'10110'});
    const order=await createOrder(owner,{conversation_id:conv.id,recipient_name:'ผู้ทดสอบ',phone:'0812345678',address:'ที่อยู่ทดสอบ',postcode:'10110',items:[{name:'สินค้า',variant:'ทดสอบ',qty:1,unit_price:290,total:290}],subtotal:290,shipping_fee:40,discount:0,total:330,payment_method:'transfer',internal_note:null});
    await expect(updateOrder({...owner,role:'viewer'},order.id,{status:'confirmed'})).rejects.toThrow();
    const asset=randomUUID();
    await pool.query("insert into media_assets(id,conversation_id,page_id,storage_key,status,kind) values($1,$2,$3,'slip/journey.jpg','stored','slip')",[asset,conv.id,page]);
    await linkOrderMedia(owner,order.id,asset,'payment_slip');
    const paid=await updateOrder(owner,order.id,{payment_status:'paid',status:'confirmed',slip_media_id:asset}); expect(paid.payment_status).toBe('paid');
    await updateOrder(owner,order.id,{status:'packed'});
    const csv=`เลขออเดอร์,เลขพัสดุ,ขนส่ง,ชื่อผู้รับ,เบอร์ผู้รับ,รหัสไปรษณีย์\n${order.order_no},TH1234567890,Flash,ผู้ทดสอบ,0812345678,10110`;
    const imported=await createImport(owner,{filename:'journey.csv',content:csv});
    const applied=await applyImport(owner,imported.import_id,{notify_mode:'none'}); expect(applied.applied_count).toBe(1);
    await expect(applyImport(owner,imported.import_id,{notify_mode:'none'})).rejects.toThrow('ลงเลขพัสดุไปแล้ว');
    await expect(createImport(owner,{filename:'same-file-renamed.csv',content:csv})).rejects.toThrow();
    const shipped=await getOrder(owner,order.id); expect(shipped.tracking_no).toBe('TH1234567890'); expect(shipped.status).toBe('shipped');
    const dashboard=await loadDashboard(owner,'7d'); expect(dashboard.headline.sales).toBe(330); expect(dashboard.headline.order_count).toBe(1);
    const workspace=await loadWorkspace(owner,conv.id); expect(workspace.customer.phone).toBe('0812345678'); expect(workspace.orders).toHaveLength(1);
    const messages=await listMessages(owner,conv.id); expect(messages.messages.filter(m=>m.direction==='out')).toHaveLength(2);
    expect(await listSendStatuses({...owner,role:'viewer',allowed_page_ids:[]})).toHaveLength(0);
    expect(await listSendStatuses(owner)).toHaveLength(2);
  });
});
